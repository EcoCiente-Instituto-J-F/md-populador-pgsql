-- ============================================================================
-- SECAO DM3 - CARGA DO DATA MART (ETL NO SQL)
-- ----------------------------------------------------------------------------
-- PROCEDURE: sp_carga_datamart
-- Refresh completo a partir do OLTP, dentro da transacao de quem chama:
--   1. dim_tempo  : CTE RECURSIVA gera o calendario do menor ao maior dia
--                   com evento (minimo CURRENT_DATE). ON CONFLICT DO NOTHING
--                   preserva as linhas ja existentes (nao renumera nada).
--   2. dimensoes  : UPSERT pela chave natural (id_*). As surrogate keys ja
--                   existentes sao preservadas; so atributos mudam.
--   3. fatos      : TRUNCATE + recarga. Cada fato e montado em CTEs
--                   (base OLTP -> resolucao das SKs). sk_tempo e resolvida
--                   por JOIN em dim_tempo.data_completa, nunca calculada.
--   4. limpeza    : remove membros de dimensao cuja origem nao existe mais
--                   (seguro, pois os fatos acabaram de ser recarregados).
-- Se qualquer passo falhar, nada e gravado (atomicidade da transacao).
-- ============================================================================
CREATE OR REPLACE PROCEDURE sp_carga_datamart()
LANGUAGE plpgsql
AS $$
DECLARE
    v_qtd_postagens BIGINT;
    v_qtd_coletas   BIGINT;
    v_fato_post     BIGINT;
    v_fato_col      BIGINT;
BEGIN
    -- ------------------------------------------------------------------
    -- 1. dim_tempo (CTE recursiva)
    -- ------------------------------------------------------------------
    INSERT INTO dim_tempo (sk_tempo, data_completa, ano, trimestre, mes, nome_mes,
                           dia, dia_semana_numero, nome_dia_semana, is_fim_de_semana)
    WITH RECURSIVE datas_eventos AS (
        SELECT (data_postagem AT TIME ZONE 'America/Sao_Paulo')::DATE AS d FROM tb_postagens
        UNION ALL
        SELECT (data_visita AT TIME ZONE 'America/Sao_Paulo')::DATE FROM tb_visitas_coletas
    ),
    limites AS (
        SELECT LEAST(MIN(d), CURRENT_DATE)    AS data_ini,
               GREATEST(MAX(d), CURRENT_DATE) AS data_fim
          FROM datas_eventos
    ),
    calendario (data_completa) AS (
        SELECT data_ini FROM limites
        UNION ALL
        SELECT c.data_completa + 1
          FROM calendario c, limites l
         WHERE c.data_completa < l.data_fim
    )
    SELECT
        TO_CHAR(c.data_completa, 'YYYYMMDD')::INTEGER,
        c.data_completa,
        EXTRACT(YEAR    FROM c.data_completa)::INTEGER,
        EXTRACT(QUARTER FROM c.data_completa)::INTEGER,
        EXTRACT(MONTH   FROM c.data_completa)::INTEGER,
        (ARRAY['Janeiro','Fevereiro','Marco','Abril','Maio','Junho','Julho',
               'Agosto','Setembro','Outubro','Novembro','Dezembro'])[EXTRACT(MONTH FROM c.data_completa)::INTEGER],
        EXTRACT(DAY     FROM c.data_completa)::INTEGER,
        EXTRACT(DOW     FROM c.data_completa)::INTEGER,
        (ARRAY['Domingo','Segunda-feira','Terca-feira','Quarta-feira',
               'Quinta-feira','Sexta-feira','Sabado'])[EXTRACT(DOW FROM c.data_completa)::INTEGER + 1],
        EXTRACT(DOW FROM c.data_completa) IN (0, 6)
    FROM calendario c
    ON CONFLICT DO NOTHING;

    -- ------------------------------------------------------------------
    -- 2. Dimensoes (UPSERT pela chave natural)
    -- ------------------------------------------------------------------
    INSERT INTO dim_usuario (id_usuario, nome_usuario, email_usuario, tipo_usuario, ativo, carregado_em)
    SELECT u.id_usuario, u.nome_usuario, u.email_usuario, tu.nome_tipo, u.ativo, now()
      FROM tb_usuarios u
      JOIN tb_lkp_tipos_usuarios tu ON tu.id_tipo_usuario = u.tipo_usuario_id
    ON CONFLICT (id_usuario) DO UPDATE
       SET nome_usuario  = EXCLUDED.nome_usuario,
           email_usuario = EXCLUDED.email_usuario,
           tipo_usuario  = EXCLUDED.tipo_usuario,
           ativo         = EXCLUDED.ativo,
           carregado_em  = now();

    INSERT INTO dim_condominio (id_condominio, nome_condominio, tipo_condominio, cidade, estado, ativo, carregado_em)
    SELECT c.id_condominio, c.nome_condominio, tc.nome_tipo, e.cidade, e.estado, c.ativo, now()
      FROM tb_condominios c
      JOIN tb_lkp_tipos_condominios tc ON tc.id_tipo_condominio = c.tipo_condominio_id
      LEFT JOIN tb_enderecos e          ON e.id_endereco = c.endereco_id
    ON CONFLICT (id_condominio) DO UPDATE
       SET nome_condominio = EXCLUDED.nome_condominio,
           tipo_condominio = EXCLUDED.tipo_condominio,
           cidade          = EXCLUDED.cidade,
           estado          = EXCLUDED.estado,
           ativo           = EXCLUDED.ativo,
           carregado_em    = now();

    INSERT INTO dim_cooperativa (id_cooperativa, nome_cooperativa, cidade, estado, carregado_em)
    SELECT co.id_cooperativa, co.nome_cooperativa, e.cidade, e.estado, now()
      FROM tb_cooperativas co
      LEFT JOIN tb_enderecos e ON e.id_endereco = co.endereco_id
    ON CONFLICT (id_cooperativa) DO UPDATE
       SET nome_cooperativa = EXCLUDED.nome_cooperativa,
           cidade           = EXCLUDED.cidade,
           estado           = EXCLUDED.estado,
           carregado_em     = now();

    INSERT INTO dim_categoria_residuo (id_categoria, nome_categoria, permite_reciclagem,
                                       pontos_base, limite_pontos_ciclo, carregado_em)
    SELECT cr.id_categoria, cr.nome_categoria, cr.permite_reciclagem,
           cr.pontos_base, cr.limite_pontos_diario, now()
      FROM tb_lkp_categorias_residuos cr
    ON CONFLICT (id_categoria) DO UPDATE
       SET nome_categoria      = EXCLUDED.nome_categoria,
           permite_reciclagem  = EXCLUDED.permite_reciclagem,
           pontos_base         = EXCLUDED.pontos_base,
           limite_pontos_ciclo = EXCLUDED.limite_pontos_ciclo,
           carregado_em        = now();

    INSERT INTO dim_status_postagem (id_status_validacao, codigo, descricao)
    SELECT s.id_status_validacao, s.nome_status, s.descricao
      FROM tb_lkp_status_validacoes_postagens s
    ON CONFLICT (id_status_validacao) DO UPDATE
       SET codigo    = EXCLUDED.codigo,
           descricao = EXCLUDED.descricao;

    INSERT INTO dim_status_agendamento (id_status, nome_status)
    SELECT sa.id_status, sa.nome_status
      FROM tb_lkp_status_agendamentos sa
    ON CONFLICT (id_status) DO UPDATE
       SET nome_status = EXCLUDED.nome_status;

    -- ------------------------------------------------------------------
    -- 3. Fatos (refresh completo, montados em CTEs)
    -- ------------------------------------------------------------------
    TRUNCATE TABLE fato_postagens, fato_coletas;

    INSERT INTO fato_postagens (id_postagem, sk_tempo, sk_usuario, sk_condominio, sk_categoria,
                                sk_status_postagem, qtd_postagens, foi_aprovada, pontos_base_categoria)
    WITH base AS (
        SELECT p.id_postagem,
               (p.data_postagem AT TIME ZONE 'America/Sao_Paulo')::DATE AS data_evento,
               p.usuario_id, p.condominio_id, p.categoria_id, p.status_validacao_id
          FROM tb_postagens p
    ),
    resolvido AS (
        SELECT b.id_postagem,
               t.sk_tempo, du.sk_usuario, dc.sk_condominio, dcat.sk_categoria,
               dsp.sk_status_postagem,
               (dsp.codigo = 'aprovada')         AS foi_aprovada,
               COALESCE(dcat.pontos_base, 0)     AS pontos_base_categoria
          FROM base b
          JOIN dim_tempo t                  ON t.data_completa = b.data_evento
          JOIN dim_usuario du               ON du.id_usuario = b.usuario_id
          JOIN dim_condominio dc            ON dc.id_condominio = b.condominio_id
          JOIN dim_categoria_residuo dcat   ON dcat.id_categoria = b.categoria_id
          JOIN dim_status_postagem dsp      ON dsp.id_status_validacao = b.status_validacao_id
    )
    SELECT id_postagem, sk_tempo, sk_usuario, sk_condominio, sk_categoria,
           sk_status_postagem, 1, foi_aprovada, pontos_base_categoria
      FROM resolvido;

    INSERT INTO fato_coletas (id_visita_coleta, sk_tempo, sk_condominio, sk_cooperativa,
                              sk_status_agendamento, foi_realizada, houve_confirmacao, qtd_visitas)
    WITH base AS (
        SELECT v.id_visita_coleta,
               (v.data_visita AT TIME ZONE 'America/Sao_Paulo')::DATE AS data_evento,
               a.condominio_id, a.cooperativa_id, a.status_agendamento_id,
               v.foi_realizada, v.houve_confirmacao
          FROM tb_visitas_coletas v
          JOIN tb_agendamentos_coletas a ON a.id_agendamento_coleta = v.agendamento_coleta_id
    ),
    resolvido AS (
        SELECT b.id_visita_coleta, t.sk_tempo, dc.sk_condominio, dco.sk_cooperativa,
               dsa.sk_status_agendamento, b.foi_realizada, b.houve_confirmacao
          FROM base b
          JOIN dim_tempo t               ON t.data_completa = b.data_evento
          JOIN dim_condominio dc         ON dc.id_condominio = b.condominio_id
          JOIN dim_cooperativa dco       ON dco.id_cooperativa = b.cooperativa_id
          JOIN dim_status_agendamento dsa ON dsa.id_status = b.status_agendamento_id
    )
    SELECT id_visita_coleta, sk_tempo, sk_condominio, sk_cooperativa,
           sk_status_agendamento, foi_realizada, houve_confirmacao, 1
      FROM resolvido;

    -- ------------------------------------------------------------------
    -- 4. Limpeza de membros orfaos das dimensoes
    -- ------------------------------------------------------------------
    DELETE FROM dim_usuario d     WHERE NOT EXISTS (SELECT 1 FROM tb_usuarios o     WHERE o.id_usuario = d.id_usuario);
    DELETE FROM dim_condominio d  WHERE NOT EXISTS (SELECT 1 FROM tb_condominios o  WHERE o.id_condominio = d.id_condominio);
    DELETE FROM dim_cooperativa d WHERE NOT EXISTS (SELECT 1 FROM tb_cooperativas o WHERE o.id_cooperativa = d.id_cooperativa);

    -- ------------------------------------------------------------------
    -- 5. Reconciliacao: o grao dos fatos tem que bater com a origem
    -- ------------------------------------------------------------------
    SELECT COUNT(*) INTO v_qtd_postagens FROM tb_postagens;
    SELECT COUNT(*) INTO v_qtd_coletas   FROM tb_visitas_coletas;
    SELECT COUNT(*) INTO v_fato_post     FROM fato_postagens;
    SELECT COUNT(*) INTO v_fato_col      FROM fato_coletas;

    IF v_fato_post <> v_qtd_postagens OR v_fato_col <> v_qtd_coletas THEN
        RAISE EXCEPTION 'sp_carga_datamart: reconciliacao falhou (postagens % x %, coletas % x %)',
            v_qtd_postagens, v_fato_post, v_qtd_coletas, v_fato_col;
    END IF;

    RAISE NOTICE 'sp_carga_datamart: fato_postagens=%, fato_coletas=%', v_fato_post, v_fato_col;
END;
$$;
COMMENT ON PROCEDURE sp_carga_datamart() IS
    'Refresh completo e idempotente do Data Mart a partir do OLTP: dim_tempo por CTE recursiva, UPSERT das dimensoes, recarga dos fatos em CTEs e reconciliacao de contagens.';


-- ============================================================================
-- SECAO DM4 - VIEWS DE BI (CTEs + WINDOW FUNCTIONS)
-- Consomem apenas o Data Mart (fatos + dimensoes). Nenhuma expoe PII.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- BI 1: ranking mensal de condominios por postagens aprovadas
-- Window: RANK() e DENSE_RANK() particionados por ano/mes
-- ----------------------------------------------------------------------------
CREATE OR REPLACE VIEW vw_bi_ranking_condominios_mensal AS
WITH postagens_mes AS (
    SELECT t.ano,
           t.mes,
           f.sk_condominio,
           COUNT(*)::BIGINT                                         AS total_postagens,
           COUNT(*) FILTER (WHERE f.foi_aprovada)::BIGINT           AS postagens_aprovadas,
           COALESCE(SUM(f.pontos_base_categoria)
                    FILTER (WHERE f.foi_aprovada), 0)::BIGINT       AS pontos_aprovados
      FROM fato_postagens f
      JOIN dim_tempo t ON t.sk_tempo = f.sk_tempo
     GROUP BY t.ano, t.mes, f.sk_condominio
)
SELECT pm.ano,
       pm.mes,
       dc.id_condominio,
       dc.nome_condominio,
       dc.tipo_condominio,
       pm.total_postagens,
       pm.postagens_aprovadas,
       pm.pontos_aprovados,
       ROUND(100.0 * pm.postagens_aprovadas / NULLIF(pm.total_postagens, 0), 2) AS taxa_aprovacao_pct,
       RANK()       OVER (PARTITION BY pm.ano, pm.mes ORDER BY pm.postagens_aprovadas DESC) AS posicao_rank,
       DENSE_RANK() OVER (PARTITION BY pm.ano, pm.mes ORDER BY pm.postagens_aprovadas DESC) AS posicao_dense_rank
  FROM postagens_mes pm
  JOIN dim_condominio dc ON dc.sk_condominio = pm.sk_condominio;
COMMENT ON VIEW vw_bi_ranking_condominios_mensal IS
    'BI | Grao: condominio x mes. Ranking de condominios por postagens aprovadas (RANK e DENSE_RANK por mes).';

-- ----------------------------------------------------------------------------
-- BI 2: running total de postagens aprovadas e pontos por usuario
-- Window: SUM() OVER (PARTITION BY usuario ORDER BY dia ROWS UNBOUNDED PRECEDING)
-- ----------------------------------------------------------------------------
CREATE OR REPLACE VIEW vw_bi_postagens_acumuladas_usuario AS
WITH postagens_dia AS (
    SELECT f.sk_usuario,
           t.data_completa,
           COUNT(*) FILTER (WHERE f.foi_aprovada)::BIGINT                    AS aprovadas_no_dia,
           COALESCE(SUM(f.pontos_base_categoria)
                    FILTER (WHERE f.foi_aprovada), 0)::BIGINT                AS pontos_no_dia
      FROM fato_postagens f
      JOIN dim_tempo t ON t.sk_tempo = f.sk_tempo
     GROUP BY f.sk_usuario, t.data_completa
)
SELECT du.id_usuario,
       du.nome_usuario,
       du.tipo_usuario,
       pd.data_completa,
       pd.aprovadas_no_dia,
       pd.pontos_no_dia,
       SUM(pd.aprovadas_no_dia) OVER w AS aprovadas_acumuladas,
       SUM(pd.pontos_no_dia)    OVER w AS pontos_acumulados
  FROM postagens_dia pd
  JOIN dim_usuario du ON du.sk_usuario = pd.sk_usuario
WINDOW w AS (PARTITION BY pd.sk_usuario ORDER BY pd.data_completa ROWS UNBOUNDED PRECEDING);
COMMENT ON VIEW vw_bi_postagens_acumuladas_usuario IS
    'BI | Grao: usuario x dia com postagem. Running total de postagens aprovadas e pontos teoricos aprovados. Sem e-mail (PII).';

-- ----------------------------------------------------------------------------
-- BI 3: evolucao mensal das coletas por cooperativa
-- Window: LAG() para variacao mes a mes
-- ----------------------------------------------------------------------------
CREATE OR REPLACE VIEW vw_bi_evolucao_coletas_mensal AS
WITH coletas_mes AS (
    SELECT f.sk_cooperativa,
           t.ano,
           t.mes,
           SUM(f.qtd_visitas)::BIGINT                              AS visitas_agendadas,
           COUNT(*) FILTER (WHERE f.foi_realizada)::BIGINT         AS coletas_realizadas
      FROM fato_coletas f
      JOIN dim_tempo t ON t.sk_tempo = f.sk_tempo
     GROUP BY f.sk_cooperativa, t.ano, t.mes
),
com_anterior AS (
    SELECT cm.*,
           LAG(cm.coletas_realizadas) OVER (PARTITION BY cm.sk_cooperativa
                                            ORDER BY cm.ano, cm.mes) AS realizadas_mes_anterior
      FROM coletas_mes cm
)
SELECT dco.id_cooperativa,
       dco.nome_cooperativa,
       ca.ano,
       ca.mes,
       ca.visitas_agendadas,
       ca.coletas_realizadas,
       ROUND(100.0 * ca.coletas_realizadas / NULLIF(ca.visitas_agendadas, 0), 2) AS taxa_comparecimento_pct,
       ca.realizadas_mes_anterior,
       ca.coletas_realizadas - ca.realizadas_mes_anterior                         AS variacao_absoluta,
       ROUND(100.0 * (ca.coletas_realizadas - ca.realizadas_mes_anterior)
             / NULLIF(ca.realizadas_mes_anterior, 0), 2)                          AS variacao_pct
  FROM com_anterior ca
  JOIN dim_cooperativa dco ON dco.sk_cooperativa = ca.sk_cooperativa;
COMMENT ON VIEW vw_bi_evolucao_coletas_mensal IS
    'BI | Grao: cooperativa x mes. Coletas realizadas, taxa de comparecimento e variacao mes a mes (LAG).';

-- ----------------------------------------------------------------------------
-- BI 4: DAU com media movel de 7 dias
-- Window: AVG() OVER (ORDER BY dia ROWS BETWEEN 6 PRECEDING AND CURRENT ROW)
-- ----------------------------------------------------------------------------
CREATE OR REPLACE VIEW vw_bi_dau_media_movel AS
WITH dau_dia AS (
    SELECT m.data_referencia, m.dau, m.wau, m.mau, m.novos_usuarios, m.stickiness
      FROM tb_metricas_dau m
)
SELECT t.sk_tempo,
       d.data_referencia,
       t.nome_dia_semana,
       d.dau,
       d.wau,
       d.mau,
       d.novos_usuarios,
       d.stickiness,
       ROUND(AVG(d.dau) OVER (ORDER BY d.data_referencia
                              ROWS BETWEEN 6 PRECEDING AND CURRENT ROW), 2) AS dau_media_movel_7d,
       d.dau - LAG(d.dau, 7) OVER (ORDER BY d.data_referencia)               AS variacao_vs_semana_anterior
  FROM dau_dia d
  LEFT JOIN dim_tempo t ON t.data_completa = d.data_referencia;
COMMENT ON VIEW vw_bi_dau_media_movel IS
    'BI | Grao: dia. DAU/WAU/MAU com media movel de 7 dias e variacao contra o mesmo dia da semana anterior.';


