-- ============================================================================
-- ECOCIENTE | DATA MART (STAR SCHEMA) + VIEWS DE BI
-- Dialeto: PostgreSQL 14+
--
-- Pre-requisito: sql/ecociente_schema.sql aplicado (OLTP normalizado).
-- Ordem de execucao: ecociente_schema.sql -> ecociente_datamart.sql -> populador
--                    -> notebook Databricks (le as 9 tabelas abaixo).
--
-- Conteudo:
--   SECAO DM1 - DIMENSOES      : dim_tempo, dim_usuario, dim_condominio,
--                                dim_cooperativa, dim_categoria_residuo,
--                                dim_status_postagem, dim_status_agendamento
--   SECAO DM2 - FATOS          : fato_postagens (1 linha por postagem)
--                                fato_coletas   (1 linha por visita de coleta)
--   SECAO DM3 - CARGA (ETL)    : sp_carga_datamart() -> refresh completo,
--                                transacional e idempotente, a partir do OLTP.
--                                dim_tempo gerada com CTE RECURSIVA.
--   SECAO DM4 - VIEWS DE BI    : vw_bi_* com CTEs e WINDOW FUNCTIONS
--                                (RANK, DENSE_RANK, SUM OVER, LAG, AVG OVER)
--
-- Compatibilidade: a estrutura das 9 tabelas e identica a do banco de producao
-- (Neon). CREATE TABLE IF NOT EXISTS nao altera tabelas ja existentes; num
-- banco novo as surrogate keys usam IDENTITY (equivalente as sequences de la).
-- O script pode ser executado mais de uma vez com seguranca.
-- ============================================================================

BEGIN;

-- ============================================================================
-- SECAO DM1 - DIMENSOES
-- ============================================================================

-- Calendario diario. sk_tempo e chave inteligente YYYYMMDD (sem sequence).
CREATE TABLE IF NOT EXISTS dim_tempo (
    sk_tempo            INTEGER      NOT NULL,
    data_completa       DATE         NOT NULL,
    ano                 INTEGER      NOT NULL,
    trimestre           INTEGER      NOT NULL,
    mes                 INTEGER      NOT NULL,
    nome_mes            VARCHAR(20)  NOT NULL,
    dia                 INTEGER      NOT NULL,
    dia_semana_numero   INTEGER      NOT NULL,
    nome_dia_semana     VARCHAR(20)  NOT NULL,
    is_fim_de_semana    BOOLEAN      NOT NULL,
    CONSTRAINT dim_tempo_pkey PRIMARY KEY (sk_tempo),
    CONSTRAINT dim_tempo_data_completa_key UNIQUE (data_completa)
);
COMMENT ON TABLE dim_tempo IS 'Dimensao temporal compartilhada pelos fatos do Data Mart. Grao: 1 linha por dia civil (America/Sao_Paulo).';
COMMENT ON COLUMN dim_tempo.sk_tempo IS 'Chave inteligente YYYYMMDD';
COMMENT ON COLUMN dim_tempo.dia_semana_numero IS '0 = domingo ... 6 = sabado (EXTRACT(DOW))';

CREATE TABLE IF NOT EXISTS dim_usuario (
    sk_usuario      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario      INTEGER      NOT NULL,
    nome_usuario    VARCHAR(100),
    email_usuario   VARCHAR(255),
    tipo_usuario    VARCHAR(50),
    ativo           BOOLEAN,
    carregado_em    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT dim_usuario_pkey PRIMARY KEY (sk_usuario),
    CONSTRAINT dim_usuario_id_usuario_key UNIQUE (id_usuario)
);
COMMENT ON TABLE dim_usuario IS 'Dimensao de usuarios (origem tb_usuarios + tb_lkp_tipos_usuarios). Grao: 1 linha por usuario.';
COMMENT ON COLUMN dim_usuario.email_usuario IS 'PII - mantida por compatibilidade com o banco de producao. Nao expor em views de BI.';

CREATE TABLE IF NOT EXISTS dim_condominio (
    sk_condominio   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_condominio   INTEGER      NOT NULL,
    nome_condominio VARCHAR(255),
    tipo_condominio VARCHAR(50),
    cidade          VARCHAR(100),
    estado          CHAR(2),
    ativo           BOOLEAN,
    carregado_em    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT dim_condominio_pkey PRIMARY KEY (sk_condominio),
    CONSTRAINT dim_condominio_id_condominio_key UNIQUE (id_condominio)
);
COMMENT ON TABLE dim_condominio IS 'Dimensao de condominios (origem tb_condominios + tipo + endereco). Grao: 1 linha por condominio.';

CREATE TABLE IF NOT EXISTS dim_cooperativa (
    sk_cooperativa   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_cooperativa   INTEGER      NOT NULL,
    nome_cooperativa VARCHAR(255),
    cidade           VARCHAR(100),
    estado           CHAR(2),
    carregado_em     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT dim_cooperativa_pkey PRIMARY KEY (sk_cooperativa),
    CONSTRAINT dim_cooperativa_id_cooperativa_key UNIQUE (id_cooperativa)
);
COMMENT ON TABLE dim_cooperativa IS 'Dimensao de cooperativas (origem tb_cooperativas + endereco). Grao: 1 linha por cooperativa.';

CREATE TABLE IF NOT EXISTS dim_categoria_residuo (
    sk_categoria        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_categoria        INTEGER      NOT NULL,
    nome_categoria      VARCHAR(100),
    permite_reciclagem  BOOLEAN,
    pontos_base         INTEGER,
    limite_pontos_ciclo INTEGER,
    carregado_em        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT dim_categoria_residuo_pkey PRIMARY KEY (sk_categoria),
    CONSTRAINT dim_categoria_residuo_id_categoria_key UNIQUE (id_categoria)
);
COMMENT ON TABLE dim_categoria_residuo IS 'Dimensao de categorias de residuo (origem tb_lkp_categorias_residuos). Grao: 1 linha por categoria.';
COMMENT ON COLUMN dim_categoria_residuo.limite_pontos_ciclo IS 'Origem: tb_lkp_categorias_residuos.limite_pontos_diario (teto por ciclo diario)';

CREATE TABLE IF NOT EXISTS dim_status_postagem (
    sk_status_postagem  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_status_validacao INTEGER      NOT NULL,
    codigo              VARCHAR(30)  NOT NULL,
    descricao           VARCHAR(255),
    CONSTRAINT dim_status_postagem_pkey PRIMARY KEY (sk_status_postagem),
    CONSTRAINT dim_status_postagem_codigo_key UNIQUE (codigo),
    CONSTRAINT dim_status_postagem_id_status_validacao_key UNIQUE (id_status_validacao)
);
COMMENT ON TABLE dim_status_postagem IS 'Dimensao de status de validacao de postagens (aprovada | em_analise | reprovada).';

CREATE TABLE IF NOT EXISTS dim_status_agendamento (
    sk_status_agendamento INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_status             INTEGER      NOT NULL,
    nome_status           VARCHAR(50),
    CONSTRAINT dim_status_agendamento_pkey PRIMARY KEY (sk_status_agendamento),
    CONSTRAINT dim_status_agendamento_id_status_key UNIQUE (id_status)
);
COMMENT ON TABLE dim_status_agendamento IS 'Dimensao de status de agendamento de coleta.';


