COMMENT ON TABLE fato_postagens IS 'Fato de postagens de reciclagem. Grao: 1 linha por postagem (tb_postagens). Medidas: qtd_postagens, foi_aprovada, pontos_base_categoria.';
COMMENT ON COLUMN fato_postagens.pontos_base_categoria IS 'Pontos base da categoria na configuracao atual, inclusive em postagens nao aprovadas (ponto teorico). Filtrar foi_aprovada para pontos efetivos.';

